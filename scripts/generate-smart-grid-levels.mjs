// Pre-generates the 聰明格 (Smart Grid) level bank: 50 puzzles per difficulty,
// each verified to have exactly one solution before being accepted. Run with:
//   node --experimental-strip-types scripts/generate-smart-grid-levels.mjs
import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import {
  generateSmartGridPuzzle,
  countSolutions,
  SMART_GRID_DIFFICULTY,
  SMART_GRID_DIFFICULTIES,
} from '../src/lib/smartGrid.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const COUNT_PER_DIFFICULTY = 50;
const MAX_ATTEMPTS_PER_PUZZLE = 3000;

const levels = [];

for (const difficulty of SMART_GRID_DIFFICULTIES) {
  const config = SMART_GRID_DIFFICULTY[difficulty];
  let made = 0;
  let totalAttempts = 0;

  while (made < COUNT_PER_DIFFICULTY && totalAttempts < MAX_ATTEMPTS_PER_PUZZLE * COUNT_PER_DIFFICULTY) {
    totalAttempts++;
    const puzzle = generateSmartGridPuzzle(config.size, config);
    if (countSolutions(puzzle, 2) !== 1) continue;
    made++;
    levels.push({ id: `${difficulty}-${String(made).padStart(2, '0')}`, difficulty, ...puzzle });
  }

  if (made < COUNT_PER_DIFFICULTY) {
    console.warn(`⚠ ${difficulty}: only ${made}/${COUNT_PER_DIFFICULTY} unique puzzles after ${totalAttempts} attempts`);
  } else {
    console.log(`✓ ${difficulty}: ${made} unique puzzles (${totalAttempts} attempts)`);
  }
}

// Compact custom formatter — plain JSON.stringify(..., null, 2) explodes every
// number onto its own line, which balloons this file to ~25k lines. Keep each
// grid row / cage on one line instead.
function formatLevel(level) {
  const matrix = (rows) => `[\n      ${rows.map((row) => `[${row.join(', ')}]`).join(',\n      ')}\n    ]`;
  const cages = level.cages
    .map((cage) => `      { "id": ${cage.id}, "cells": [${cage.cells.map((cell) => `[${cell[0]}, ${cell[1]}]`).join(', ')}], "sum": ${cage.sum} }`)
    .join(',\n');
  return `  {
    "id": "${level.id}",
    "difficulty": "${level.difficulty}",
    "n": ${level.n},
    "solution": ${matrix(level.solution)},
    "cageId": ${matrix(level.cageId)},
    "cages": [
${cages}
    ]
  }`;
}

const header = `// Auto-generated by scripts/generate-smart-grid-levels.mjs — do not hand-edit.
// 50 puzzles per difficulty, each pre-verified to have exactly one solution.
import type { SmartGridLevel } from '@/lib/smartGrid';

export const SMART_GRID_LEVELS: SmartGridLevel[] = [
`;

const body = levels.map(formatLevel).join(',\n') + '\n];\n';
writeFileSync(join(__dirname, '../src/data/smartGridLevels.ts'), header + body);
console.log(`Wrote ${levels.length} levels to src/data/smartGridLevels.ts`);
